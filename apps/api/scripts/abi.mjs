// Writes contract ABIs from the Foundry build output into src/abi as typed TypeScript consts.
// Run `forge build` in contracts/ first. The output is committed, so the API builds without Foundry.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");
const dest = resolve(here, "../src/abi");

const contracts = ["CreditVault", "MockUSDT"];

mkdirSync(dest, { recursive: true });
for (const name of contracts) {
  const file = resolve(out, `${name}.sol/${name}.json`);
  if (!existsSync(file)) {
    console.error(`Missing ${file}. Run \`forge build\` in contracts/ first.`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  const body = `// Generated by scripts/abi.mjs from contracts/out. Do not edit.\nexport const ${lowerFirst(name)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(resolve(dest, `${name}.ts`), body);
  console.log(`abi: ${name} (${abi.length} entries)`);
}

function lowerFirst(s) {
  return s[0].toLowerCase() + s.slice(1);
}
